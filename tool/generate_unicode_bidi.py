"""Generate first-strong lookup data from Python's Unicode Character Database.

Only L, R and AL are strong. Emoji, numbers and combining marks are not.
Run with Python using Unicode 16.0.0 to reproduce the checked-in table.
"""
from pathlib import Path
import unicodedata

ranges = []
active = 0
start = 0
for code in range(0x110000):
    bidi = unicodedata.bidirectional(chr(code))
    kind = 1 if bidi == 'L' else -1 if bidi in ('R', 'AL') else 0
    if kind != active:
        if active:
            ranges.extend((start, code - 1, active))
        start, active = code, kind
if active:
    ranges.extend((start, 0x10FFFF, active))
lines = ['// Generated by tool/generate_unicode_bidi.py; Unicode ' + unicodedata.unidata_version + '.',
         '// Triples: inclusive start, inclusive end, direction (1=L, -1=R/AL).',
         'const strongBidiRanges = <int>[']
lines.extend(f'  0x{ranges[i]:x}, 0x{ranges[i+1]:x}, {ranges[i+2]},' for i in range(0, len(ranges), 3))
lines.append('];')
Path('lib/core/unicode_bidi_ranges.dart').write_text('\n'.join(lines) + '\n')
